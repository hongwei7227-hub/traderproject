"""Analyst coverage and billing, proxied from the services that own them.

Both routers are thin. Their job is to turn a service being unavailable into
something a page can render, rather than into a 500 that says nothing about
whether the rest of the platform is fine.

503 is used deliberately for that, with `Retry-After`. A 500 would suggest this
platform is broken; a 503 says a dependency is, which is both true and
actionable — the caller can show the rest of the page and try again.
"""

from __future__ import annotations

from typing import Annotated

from fastapi import APIRouter, Depends, HTTPException, Query, Response, status
from pydantic import BaseModel, Field

from kairos.adapters.services.http import ServiceUnavailable
from kairos.core.tenancy.context import current_scope

router = APIRouter(tags=["market"])


def get_analyst():  # type: ignore[no-untyped-def]
    raise NotImplementedError("analyst client is not wired")


def get_billing():  # type: ignore[no-untyped-def]
    raise NotImplementedError("billing client is not wired")


# ---------------------------------------------------------------------------
# Wire shapes
# ---------------------------------------------------------------------------


class GradeResponse(BaseModel):
    firm: str
    from_grade: str
    to_grade: str
    action: str


class RatingResponse(BaseModel):
    symbol: str
    company_name: str
    consensus: str
    target_price: float | None
    target_high: float | None
    target_low: float | None
    analyst_count: int
    recent_grades: list[GradeResponse]
    updated_at: str | None
    upside: float | None = Field(
        default=None,
        description=(
            "Fraction between the given price and the consensus target. Null "
            "when either is missing — showing zero would assert fair value."
        ),
    )


class PlanResponse(BaseModel):
    id: int
    name: str
    price: str
    duration_days: int
    monthly_price: str


class PlanList(BaseModel):
    plans: list[PlanResponse]


class MembershipResponse(BaseModel):
    level: int
    active: bool
    expires_at: str | None


class RechargeRequest(BaseModel):
    plan_id: int
    request_id: Annotated[str, Field(min_length=1, max_length=64)] = Field(
        description=(
            "Idempotency key, generated by the client. A double-clicked buy "
            "must produce one order, which is only possible if both requests "
            "carry the same key."
        )
    )


class RechargeResponse(BaseModel):
    id: int
    plan_id: int
    amount: str
    state: str
    awaiting_payment: bool
    created_at: str | None
    paid_at: str | None


# ---------------------------------------------------------------------------
# Analyst
# ---------------------------------------------------------------------------


@router.get("/stocks/{symbol}/analyst", response_model=RatingResponse)
async def analyst_rating(
    symbol: str,
    price: Annotated[float | None, Query(gt=0)] = None,
    analyst=Depends(get_analyst),  # type: ignore[no-untyped-def]
) -> RatingResponse:
    """What the street thinks of a symbol.

    `price` is optional and only used to compute the upside. Taken as a
    parameter rather than fetched here because the caller is usually rendering
    a page that already has a live price, and fetching a second one would show
    two different numbers on the same screen.
    """
    try:
        rating = await analyst.rating(symbol)
    except ServiceUnavailable as unavailable:
        raise _degraded(unavailable) from unavailable

    if rating is None:
        # An uncovered symbol is not an error, but there is nothing to return.
        # 404 rather than an empty rating, because an empty rating rendered in
        # a card looks like coverage that says nothing.
        raise HTTPException(
            status.HTTP_404_NOT_FOUND, f"No analyst coverage for {symbol.upper()}"
        )

    return RatingResponse(
        symbol=rating.symbol,
        company_name=rating.company_name,
        consensus=rating.consensus,
        target_price=rating.target_price,
        target_high=rating.target_high,
        target_low=rating.target_low,
        analyst_count=rating.analyst_count,
        recent_grades=[
            GradeResponse(
                firm=g.firm, from_grade=g.from_grade, to_grade=g.to_grade, action=g.action
            )
            for g in rating.recent_grades
        ],
        updated_at=rating.updated_at.isoformat() if rating.updated_at else None,
        upside=rating.upside_from(price) if price else None,
    )


@router.get("/stocks/cache-stats")
async def analyst_cache_stats(
    analyst=Depends(get_analyst),  # type: ignore[no-untyped-def]
) -> dict[str, int]:
    """The analyst service's own cache counters.

    Exposed because a two-level cache whose hit rate nobody can see is a
    two-level cache nobody can tune.
    """
    try:
        return await analyst.cache_stats()
    except ServiceUnavailable as unavailable:
        raise _degraded(unavailable) from unavailable


