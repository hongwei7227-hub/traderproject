@router.get("/billing/plans", response_model=PlanList)
async def list_plans(
    billing=Depends(get_billing),  # type: ignore[no-untyped-def]
) -> PlanList:
    try:
        plans = await billing.plans()
    except ServiceUnavailable as unavailable:
        raise _degraded(unavailable) from unavailable

    return PlanList(
        plans=[
            PlanResponse(
                id=p.id,
                name=p.name,
                price=str(p.price),
                duration_days=p.duration_days,
                monthly_price=str(p.monthly_price),
            )
            for p in plans
        ]
    )


@router.get("/billing/membership", response_model=MembershipResponse)
async def membership(
    billing=Depends(get_billing),  # type: ignore[no-untyped-def]
) -> MembershipResponse:
    """The caller's own entitlement.

    The user is taken from the verified scope, never from a parameter. A user
    id a client could supply is a user id a client could change.
    """
    scope = current_scope()
    try:
        found = await billing.membership(str(scope.user_id))
    except ServiceUnavailable as unavailable:
        raise _degraded(unavailable) from unavailable

    return MembershipResponse(
        level=found.level,
        active=found.active,
        expires_at=found.expires_at.isoformat() if found.expires_at else None,
    )


@router.post(
    "/billing/recharge",
    status_code=status.HTTP_201_CREATED,
    response_model=RechargeResponse,
)
async def start_recharge(
    request: RechargeRequest,
    billing=Depends(get_billing),  # type: ignore[no-untyped-def]
) -> RechargeResponse:
    """Create an unpaid order.

    201 here, unlike an order proposal: the recharge service creates the row
    synchronously and hands back its id, so the thing described by the response
    genuinely exists by the time it arrives.
    """
    scope = current_scope()
    try:
        order = await billing.start_recharge(
            str(scope.user_id), request.plan_id, request_id=request.request_id
        )
    except ServiceUnavailable as unavailable:
        raise _degraded(unavailable) from unavailable

    return _recharge(order)


@router.get("/billing/recharge/{order_id}", response_model=RechargeResponse)
async def recharge_status(
    order_id: int,
    billing=Depends(get_billing),  # type: ignore[no-untyped-def]
) -> RechargeResponse:
    scope = current_scope()
    try:
        order = await billing.order(str(scope.user_id), order_id)
    except ServiceUnavailable as unavailable:
        raise _degraded(unavailable) from unavailable

    if order is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, "Order not found")
    return _recharge(order)


def _recharge(order) -> RechargeResponse:  # type: ignore[no-untyped-def]
    return RechargeResponse(
        id=order.id,
        plan_id=order.plan_id,
        amount=str(order.amount),
        state=order.state.name.lower(),
        awaiting_payment=order.awaiting_payment,
        created_at=order.created_at.isoformat() if order.created_at else None,
        paid_at=order.paid_at.isoformat() if order.paid_at else None,
    )


def _degraded(unavailable: ServiceUnavailable) -> HTTPException:
    """A dependency is down, and saying so is more useful than a 500.

    `Retry-After` is short because these outages are usually a restart rather
    than an incident, and a client that waits a minute to retry a service that
    came back in two seconds looks broken to the person watching it.
    """
    return HTTPException(
        status.HTTP_503_SERVICE_UNAVAILABLE,
        f"{unavailable.service} is unavailable",
        headers={"Retry-After": "5"},
    )


